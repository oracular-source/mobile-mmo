GOLD=(255,210,122);TXT=(225,225,225);DIM=(165,165,165)

def button(im,x,y,shape,col,label,bw=108,bh=98):
    d=ImageDraw.Draw(im)
    d.rectangle([x,y,x+bw,y+bh],fill=(43,43,43),outline=(138,138,138),width=2)
    im.paste(icon(shape,col).resize((56,56),Image.NEAREST),(x+bw//2-28,y+8))
    tw=d.textlength(label,font=FS);d.text((x+bw/2-tw/2,y+72),label,font=FS,fill=(235,235,235))

def sheet(classes,path,part):
    W=1080;im=Image.new('RGB',(W,3000),(20,18,26));d=ImageDraw.Draw(im)
    d.text((30,20),'Spell icons, option B (rough draft) - part '+part,font=FB,fill=TXT)
    d.text((30,56),'Big = 2x button size. Small strip = about real size on a phone. * = new shape.',font=FS,fill=DIM)
    y=96
    for c in classes:
        d.text((30,y),NAMES[c],font=F,fill=GOLD)
        x=260   # real-size strip next to the name
        for aid,short,col in AB[c]:im.paste(icon(SHAPE[aid],col).resize((28,28),Image.NEAREST),(x,y-2));x+=32
        y+=32;x=30
        for aid,short,col in AB[c]:
            s=SHAPE[aid];button(im,x,y,s,col,short)
            if s in NEW:d.text((x+6,y+4),'*',font=FS,fill=GOLD)
            x+=114
        y+=114
    im.crop((0,0,W,y+10)).save(path)

